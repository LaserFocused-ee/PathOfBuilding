// Writes docs/API.md and the README route list from the route table: `npm run docs`. A test fails when either is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { toolDefs } from "./mcp.js";
import { action, routes, TOOLS } from "./routes.js";

const schemaText = (s: z.ZodType) => JSON.stringify(z.toJSONSchema(s, { io: "input", unrepresentable: "any" }));

export function apiDoc(): string {
  const out: string[] = [
    "# Path of Building API",
    "",
    "Generated from `server/src/routes.ts` by `npm run docs`; do not edit by hand.",
    "",
    "Every `/v1` route and `POST /mcp` need `Authorization: Bearer <POB_API_TOKEN>`. `GET /health` is open; `GET /health/deep` needs the bearer token, or `POB_HEALTH_TOKEN` in `x-health-token` when that is set. After `POB_AUTH_FAILURES_PER_MINUTE` (default 30) failed credential checks in a minute, requests without a valid credential get 429 with `Retry-After`.",
    "",
    "Replies are `{ \"ok\": true, \"result\": ..., \"warnings\": [...] }` or `{ \"ok\": false, \"error\": { \"code\", \"message\" } }`. Error codes: `not_found` 404, `invalid_input` 400, `unauthorized` 401, `stale_revision` 409, `payload_too_large` 413, `rate_limited` 429, `worker_error` 500, `unsupported` 501, `upstream_fetch_failed` 502, `worker_timeout` 504.",
    "",
    "A write that changes a build answers `{ \"result\": <the operation's own answer>, \"changed\": <sidebar stats before and after>, \"revision\": <new revision> }` inside the reply's `result`, so its own fields sit at `.result.result` (the new item's `id`, a copy's `sets`, a group's index); the reply's `.result.id` or `.result.sets` is always absent. Each route's Result below shows this shape.",
    "",
    "GET inputs go in the query string (lists comma-separated); POST and PUT inputs are a JSON body only (a query string on them is refused); path parameters are part of the input.",
    "",
    "## Known upstream calculation gaps",
    "",
    "Path of Building's own calculation, kept as it is; `stats/sidebar` and `stats/warnings` name each case on the build with an `Engine note:` line.",
    "",
    "- Runegrafts \"Limited to N\": the limit is not enforced, so every allocated copy counts and the figure is inflated by each extra copy's mods.",
    "- Magnitude bases (Focused Amulet): a crafted item's stored lines are taken as the affix rolls and scaled by the item's magnitude; a line stored at its in-game value (already scaled, above the affix's maximum) is scaled again, inflating it by the magnitude factor.",
    "- Typed minion counts (Raise Spectre's count box) are not capped at the minion limit, so Full DPS counts every typed minion.",
    "- Gems in a group are not capped at the item's sockets, so every enabled gem counts.",
    "- Config custom modifiers apply with nothing behind them; a creator's file can carry rage, added damage or resistances this way.",
    "- Calculator comparisons (what_if, compare_item, trade scoring) leave out the skills a swapped-in item grants; the swapped-out item's granted skills are left out by this API, as equipping it does.",
    "",
    "## MCP tools",
    "",
    "| Tool | Read-only | Actions |",
    "| --- | --- | --- |",
  ];
  for (const d of toolDefs()) out.push(`| \`${d.name}\` | ${d.readOnly ? "yes" : "no"} | ${d.routes.map((r) => `\`${action(r)}\``).join(", ")} |`);
  const unrouted = Object.entries(TOOLS).filter(([dom]) => !routes.some((r) => r.domain === dom && !r.stream)).map(([, t]) => `\`${t}\``);
  if (unrouted.length) out.push("", `Not yet routed (no actions, so not listed by the server): ${unrouted.join(", ")}.`);
  out.push("", "## Routes", "");
  for (const r of routes) {
    out.push(`### \`${r.method} ${r.path}\``, "", `${r.summary}`, "");
    out.push(`- Name: \`${r.name}\`${r.stream ? " (event stream, HTTP only)" : ` (MCP \`${TOOLS[r.domain]}\` action \`${action(r)}\`)`}`);
    out.push(`- Read-only: ${r.readOnly ? "yes" : "no"}; worker: \`${r.workerOp}\``);
    out.push(`- Input: \`${schemaText(r.input)}\``);
    out.push(`- Result: \`${schemaText(r.output)}\``, "");
  }
  return `${out.join("\n").trimEnd()}\n`;
}

/** The route list in README.md, between the routes markers. */
export function routeTable(): string {
  const rows = routes.map((r) => `| \`${r.method} ${r.path}\` | ${r.stream ? "HTTP only" : `\`${TOOLS[r.domain]}\` \`${action(r)}\``} | ${r.summary} |`);
  return ["| Route | MCP tool and action | What it does |", "| --- | --- | --- |", ...rows].join("\n");
}

export const START = "<!-- routes:start (generated by npm run docs) -->";
export const END = "<!-- routes:end -->";

export function readmeWithRoutes(readme: string): string {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error("README.md has no routes markers");
  return `${readme.slice(0, a + START.length)}\n${routeTable()}\n${readme.slice(b)}`;
}

if (process.argv[1]?.endsWith("gen-api-doc.js")) {
  const apiDir = process.argv[2];
  if (!apiDir) throw new Error("usage: gen-api-doc <api directory>");
  writeFileSync(join(apiDir, "docs/API.md"), apiDoc());
  const readme = join(apiDir, "README.md");
  writeFileSync(readme, readmeWithRoutes(readFileSync(readme, "utf8")));
}
